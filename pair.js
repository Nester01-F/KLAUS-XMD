function makeId() {
  return Math.random().toString(36).slice(2, 10);
}

const sleep = ms => new Promise(r => setTimeout(r, ms));

/* ================= Finalize: export creds + DM the session ID ================= */
async function finalize(entry) {
  if (entry.exporting || entry.sessionId || entry.closed) return;
  entry.exporting = true;
  try {
    // Export ONLY creds.json (a few KB). The rest of the folder (pre-keys,
    // app-state) is regenerated by WhatsApp and makes the ID far too long.
    const credsRaw = fs.readFileSync(path.join(entry.dir, 'creds.json'), 'utf8');
    JSON.parse(credsRaw); // make sure it is complete, valid JSON
    const b64 = Buffer.from(credsRaw, 'utf8').toString('base64');

    // Show it on the web page immediately; the DM continues in the background
    entry.sessionId = b64;
    entry.status = 'ready';

    try {
      const sock = entry.sock;
      const me = jidNormalizedUser(sock.user.id);
      if (b64.length <= 60000) {
        await sock.sendMessage(me, { text: b64 });
      } else {
        await sock.sendMessage(me, {
          document: Buffer.from(b64, 'utf8'),
          mimetype: 'text/plain',
          fileName: 'session-id.txt',
          caption: 'SESSION_ID (open the file and copy its contents)'
        });
      }
      await sock.sendMessage(me, {
        text: `*${BOT_NAME} SESSION READY*\nPaste the message above into your bot host as SESSION_ID. Never share it with anyone.`
      });
      entry.dmSent = true;
      await sleep(1500); // let the messages flush before closing
    } catch (e) {
      console.error(`[${entry.id}] DM failed:`, e.message);
      entry.dmError = e.message;
    }

    // Stop this temporary socket WITHOUT logging out
    entry.closed = true;
    try { entry.sock?.end?.(undefined); } catch {}
  } catch (e) {
    entry.exporting = false;
    console.error(`[${entry.id}] Export failed:`, e.message);
    // creds may not be written yet: try again shortly
    if (!entry.closed) setTimeout(() => finalize(entry), 2000);
  }
}

/* ================= Socket factory (reconnects reuse the same folder) ================= */
async function createSocket(entry) {
  const { state, saveCreds } = await useMultiFileAuthState(entry.dir);

  let version;
  try {
    ({ version } = await fetchLatestBaileysVersion());
  } catch (e) {
    console.error('Version fetch failed, using Baileys default:', e.message);
  }

  const sock = makeWASocket({
    ...(version ? { version } : {}),
    logger: P({ level: 'silent' }),
    printQRInTerminal: false,
    auth: {
      creds: state.creds,
      keys: makeCacheableSignalKeyStore(state.keys, P({ level: 'silent' }))
    },
    browser: Browsers ? Browsers.ubuntu('Chrome') : ['Ubuntu', 'Chrome', '20.0.04'],
    markOnlineOnConnect: false,
    syncFullHistory: false,
    connectTimeoutMs: 60000
  });

  entry.sock = sock;
  sock.ev.on('creds.update', saveCreds);

  sock.ev.on('connection.update', async ({ connection, lastDisconnect, qr }) => {
    if (entry.closed) return;

    if (qr && entry.method === 'qr' && !state.creds.registered) {
      try {
        entry.qr = await QRCode.toDataURL(qr, {
          width: 400,
          margin: 1,
          color: { dark: '#0f0f1e', light: '#ffffff' }
        });
        entry.status = 'awaiting_scan';
      } catch (e) {
        console.error('QR gen failed:', e.message);
      }
    }

    if (connection === 'open') {
      entry.status = 'connected';
      entry.connectedAt = Date.now();
      entry.reconnects = 0;
      setTimeout(() => finalize(entry), 2500); // short pause so creds finish saving
    }

    if (connection === 'close') {
      const code = lastDisconnect?.error?.output?.statusCode;
      console.log(`[${entry.id}] closed: ${code} ${lastDisconnect?.error?.message || ''}`);

      // Already exported or finished: nothing more to do
      if (entry.sessionId) return;

      if (code === DisconnectReason.loggedOut) {
        entry.status = 'failed';
        entry.error = 'Logged out by WhatsApp. Please try again.';
        return;
      }

      // 515 (restartRequired) is expected right after pairing: open a fresh socket
      entry.reconnects = (entry.reconnects || 0) + 1;
      if (entry.reconnects > MAX_RECONNECTS) {
        entry.status = 'failed';
        entry.error = 'Could not connect to WhatsApp. Please try again.';
        return;
      }
      const delay = code === DisconnectReason.restartRequired ? 1000 : 2500;
      setTimeout(() => {
        if (entry.closed) return;
        createSocket(entry).catch(e => {
          console.error('Reconnect failed:', e.message);
          entry.status = 'failed';
          entry.error = e.message;
        });
      }, delay);
    }
  });

  return sock;
}

function destroyEntry(id, entry) {
  entry.closed = true;
  try { entry.sock?.end?.(undefined); } catch {}
  try { fs.rmSync(entry.dir, { recursive: true, force: true }); } catch {}
  sessions.delete(id);
}

/* ================= API: CREATE SESSION ================= */
app.post('/api/pair', async (req, res) => {
  const method = req.body?.method === 'qr' ? 'qr' : 'pair';
  const phone = String(req.body?.phone || '').replace(/\D/g, '');

  if (method === 'pair' && !/^\d{8,15}$/.test(phone)) {
    return res.status(400).json({ error: 'Invalid phone. Digits only, no +.' });
  }

  const id = makeId();
  const dir = path.join(os.tmpdir(), 'klaus-sess-' + id);
  fs.mkdirSync(dir, { recursive: true });

  const entry = {
    id, sock: null, dir,
    code: null, qr: null,
    status: 'starting',
    error: null,
    sessionId: null,
    method,
    reconnects: 0,
    closed: false,
    exporting: false,
    connectedAt: 0,
    createdAt: Date.now()
  };
  sessions.set(id, entry);

  try {
    const sock = await createSocket(entry);

    if (method === 'pair') {
      await sleep(3000);
      const code = await sock.requestPairingCode(phone);
      entry.code = code;
      entry.status = 'awaiting_code';
    } else {
      // QR mode: wait up to 8s for first QR
      for (let i = 0; i < 16; i++) {
        if (entry.qr) break;
        await sleep(500);
      }
    }

    res.json({
      id,
      code: entry.code,
      qr: entry.qr,
      method: entry.method,
      status: entry.status
    });
  } catch (e) {
    destroyEntry(id, entry);
    res.status(500).json({ error: e.message });
  }
});

/* ================= API: STATUS ================= */
app.get('/api/status/:id', async (req, res) => {
  const entry = sessions.get(req.params.id);
  if (!entry) return res.status(404).json({ error: 'Session not found' });

  res.json({
    status: entry.status,
    error: entry.error,
    dmSent: !!entry.dmSent,
    code: entry.code,
    qr: entry.qr,
    sessionId: entry.sessionId
  });
});

